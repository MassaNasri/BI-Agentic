"""Disposable PostgreSQL proof of C4 owner grants and rollback."""

import os
import secrets

import psycopg2
from psycopg2 import sql
from psycopg2.errors import InsufficientPrivilege

from foundation_c4_owner_schemas import OWNERS, apply, rollback, configure_runtime_roles


if os.getenv("BIAVORA_C4_DISPOSABLE") != "1":
    raise SystemExit("C4 role verifier requires BIAVORA_C4_DISPOSABLE=1.")

connection = psycopg2.connect(
    host=os.environ["DB_HOST"], port=os.environ.get("DB_PORT", "5432"),
    dbname=os.environ["DB_NAME"], user=os.environ["DB_USER"],
    password=os.environ["DB_PASSWORD"],
)
try:
    with connection:
        with connection.cursor() as cursor:
            for tables in OWNERS.values():
                for table in tables:
                    cursor.execute(sql.SQL("CREATE TABLE public.{} (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)").format(sql.Identifier(table)))
                    cursor.execute(sql.SQL("INSERT INTO public.{} (id) VALUES (7)").format(sql.Identifier(table)))
    apply(connection)
    passwords = {domain: secrets.token_urlsafe(40) for domain in OWNERS}
    configure_runtime_roles(connection, passwords)
    for domain, tables in OWNERS.items():
        with psycopg2.connect(
            host=os.environ["DB_HOST"], port=os.environ.get("DB_PORT", "5432"),
            dbname=os.environ["DB_NAME"], user=f"biavora_{domain}_runtime",
            password=passwords[domain],
        ) as runtime:
            with runtime.cursor() as cursor:
                cursor.execute("SELECT current_user, current_schema()")
                assert cursor.fetchone() == (f"biavora_{domain}_runtime", f"biavora_{domain}")
                cursor.execute(sql.SQL("SELECT id FROM {}.{} WHERE id = 7").format(
                    sql.Identifier(f"biavora_{domain}"), sql.Identifier(tables[0]),
                ))
                assert cursor.fetchone() == (7,)
                cursor.execute(sql.SQL("INSERT INTO {}.{} (id) VALUES (11)").format(
                    sql.Identifier(f"biavora_{domain}"), sql.Identifier(tables[0]),
                ))
                cursor.execute(sql.SQL("DELETE FROM {}.{} WHERE id = 11").format(
                    sql.Identifier(f"biavora_{domain}"), sql.Identifier(tables[0]),
                ))
                cursor.execute(sql.SQL("INSERT INTO {}.{} DEFAULT VALUES RETURNING id").format(
                    sql.Identifier(f"biavora_{domain}"), sql.Identifier(tables[0]),
                ))
                generated_id = cursor.fetchone()[0]
                cursor.execute(sql.SQL("DELETE FROM {}.{} WHERE id = %s").format(
                    sql.Identifier(f"biavora_{domain}"), sql.Identifier(tables[0]),
                ), (generated_id,))
                foreign = "integration" if domain != "integration" else "query"
                target = OWNERS[foreign][0]
                for operation in (
                    sql.SQL("INSERT INTO {}.{} (id) VALUES (8)"),
                    sql.SQL("UPDATE {}.{} SET id = 8 WHERE id = 7"),
                    sql.SQL("DELETE FROM {}.{} WHERE id = 7"),
                ):
                    try:
                        cursor.execute(operation.format(sql.Identifier(f"biavora_{foreign}"), sql.Identifier(target)))
                    except InsufficientPrivilege:
                        runtime.rollback()
                    else:
                        raise AssertionError(f"{domain} runtime wrote into {foreign} domain")
    connection.autocommit = True
    with connection.cursor() as cursor:
        for domain, tables in OWNERS.items():
            own = tables[0]
            cursor.execute(sql.SQL("SET ROLE {}").format(sql.Identifier(f"biavora_{domain}_app")))
            cursor.execute(sql.SQL("SELECT id FROM {}.{} WHERE id = 7").format(
                sql.Identifier(f"biavora_{domain}"), sql.Identifier(own),
            ))
            assert cursor.fetchone() == (7,)
            cursor.execute(sql.SQL("INSERT INTO {}.{} (id) VALUES (8)").format(
                sql.Identifier(f"biavora_{domain}"), sql.Identifier(own),
            ))
            cursor.execute(sql.SQL("UPDATE {}.{} SET id = 9 WHERE id = 8").format(
                sql.Identifier(f"biavora_{domain}"), sql.Identifier(own),
            ))
            cursor.execute(sql.SQL("DELETE FROM {}.{} WHERE id = 9").format(
                sql.Identifier(f"biavora_{domain}"), sql.Identifier(own),
            ))
            foreign = "integration" if domain != "integration" else "query"
            target = OWNERS[foreign][0]
            for operation in (
                sql.SQL("INSERT INTO {}.{} (id) VALUES (8)"),
                sql.SQL("UPDATE {}.{} SET id = 8 WHERE id = 7"),
                sql.SQL("DELETE FROM {}.{} WHERE id = 7"),
            ):
                try:
                    cursor.execute(operation.format(sql.Identifier(f"biavora_{foreign}"), sql.Identifier(target)))
                except InsufficientPrivilege:
                    pass
                else:
                    raise AssertionError(f"{domain} wrote into {foreign} domain")
            cursor.execute("RESET ROLE")
    connection.autocommit = False
    rollback(connection)
    with connection.cursor() as cursor:
        for tables in OWNERS.values():
            for table in tables:
                cursor.execute(sql.SQL("SELECT id FROM public.{} WHERE id = 7").format(sql.Identifier(table)))
                assert cursor.fetchone() == (7,)
                cursor.execute("SELECT pg_get_serial_sequence(%s, 'id')", (f"public.{table}",))
                sequence = cursor.fetchone()[0]
                assert sequence is not None
                if table == tables[0]:
                    cursor.execute(sql.SQL("SELECT last_value, is_called FROM {}").format(sql.Identifier(*sequence.split('.'))))
                    last_value, is_called = cursor.fetchone()
                    assert (last_value, is_called) == (1, True)
    print("C4 owner roles: owner CRUD, foreign write denial, rollback/data preservation PASS")
finally:
    connection.close()
