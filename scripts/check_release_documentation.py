"""Check the January blueprint and optionally rebuild its non-sensitive inventory.

Documentation only: does not run application tests, recurse into TimesFM, stage
files, access secrets, or assert runtime readiness. Run from any directory.
"""
from pathlib import Path
import argparse
import re
import subprocess
from urllib.parse import unquote

ROOT = Path(__file__).resolve().parents[1]
AUDIT = ROOT / "BIAVORA_PRODUCTION_READINESS_AUDIT"
CATALOG = AUDIT / "48_DOCUMENTATION_INVENTORY_AND_SCOPE_REFERENCES.md"
TERM = re.compile(r"\bRAG\b|\bProactive[ _-]+Monitoring(?:[ _-]+Agent)?\b|\bMonitoring[ _-]+Agent\b|\bArabic\b|\bVoice[ _-]+Support\b", re.I)
CANONICAL = {20, 22, 23, 24, 25, 26, 29, 30, 31, 32, 33, 34, 43, 44, 45, 46}
SUPERSEDED = {8, 9, 10, 11, 12, 13, 14, 21}


def git(*args):
    return subprocess.check_output(["git", "-c", "core.quotepath=false", "-c", "core.safecrlf=false", *args], cwd=ROOT).decode("utf-8").splitlines()


def number(path):
    match = re.match(r"(\d\d)_", path.name)
    return int(match[1]) if match else None


def paths():
    names = set(git("ls-files")) | set(git("ls-files", "--others", "--exclude-standard"))
    result = []
    for name in sorted(names):
        if "forecasting/timesfm" in name or any(x in name.split("/") for x in ("node_modules", ".venv", "venv", "backups", "data", ".git")):
            continue
        p = ROOT / name
        if p.is_file() and not p.name.startswith(".env") and p.suffix.lower() in {".md", ".txt", ".json", ".py", ".js", ".jsx", ".ts", ".tsx", ".yaml", ".yml"}:
            if p.name not in {"package-lock.json", "pnpm-lock.yaml"} and p.stat().st_size < 2_000_000:
                result.append(p)
    return result


def classification(p, content):
    rel = p.relative_to(ROOT).as_posix()
    if p.parent == AUDIT:
        n = number(p)
        if n in CANONICAL or p.name == "README.md":
            return "B", "Current canonical planning", "Yes", "Reconciled"
        if n in SUPERSEDED:
            return "C", "Superseded supporting plan; body retained", "No", "Banner added"
        if n in {48, 49}:
            return "B", "Reconciliation record / reference catalog", "Yes", "Created"
        return "A", "Historical audit / implementation evidence", "Dated evidence", "No; preserve chronology"
    if "SUPERSEDED" in content[:1200]:
        return "C", "Superseded planning/reference; body retained", "No launch authority", "Banner added"
    if rel == "README.md":
        return "B", "Development entrypoint; canonical release links", "Yes with stated limits", "Reconciled"
    if p.suffix.lower() in {".md", ".txt"} or rel == "BIAVORA_PRODUCTION_READINESS_AUDIT/27_FINAL_AUDIT_RESULTS.json":
        return "A", "Historical report or technical reference; no January scope authority", "Revalidate for runtime", "No; reference only"
    return "D", "Existing source/configuration/tests; maintained or dormant", "Not changed", "No scope-driven deletion"


def inventory(files):
    lines = ["# 48 — Documentation inventory and retained scope references", "",
             "Generated by `python -X utf8 scripts/check_release_documentation.py --write-inventory` after the 2026-10-27 scope and local-closure decisions. Scope authority is [43](43_BIAVORA_PRODUCT_SCOPE_AND_RELEASE_ROADMAP_2027.md); current closure/CI findings are in [49](49_FOUNDATION_C_LOCAL_CLOSURE_AND_CI_REPAIR_REPORT.md), with the prior reconciliation preserved in [47](47_SCOPE_ARCHITECTURE_RECONCILIATION_REPORT.md).", "",
             "## Classification and review coverage", "",
             "A = historical evidence/technical reference retained unchanged, not January scope. B = current planning updated; excluded-feature mentions state exclusions, preserved behavior or conflicts. C = obsolete duplicate/supporting plan with an explicit supersession banner; its body is retained for history. D = source/config/test functionality retained; scope removal does not authorize deletion.", "",
             "The canonical numbered set and Foundation reports were reviewed with source-path followups; architecture, debt, scope, security, roadmap and implementation maps were reconciled. Older audit/remediation/ETL documents were inventoried and inspected by headings, claims and relevant sections, with deeper reading of ownership, transport, acceptance, recovery and release evidence. This is not a claim that every line of every ancillary technical note or source file was manually reviewed. Source paths actually traced are listed in 45. A classification is not a fresh test pass.", "",
             "Historical 00–07/15–19/27/28/35/36–42/47 and remediation reports retain dated statements and old feature plans. Report 49 supersedes their external-blocking sequencing interpretation without rewriting evidence. Existing voice/language behavior and tests remain maintained. Dormant knowledge/proactive code is deferred; none is activated or deleted. ETL operational monitoring and quality checks are distinct from the excluded business investigation agent.", "",
             "## File inventory", "", "| File | Purpose | Historical / Canonical | Current? | Needs update? |", "|---|---|---|---|---|"]
    counts = {x: 0 for x in "ABCD"}
    matches = []
    docs = 0
    for p in files:
        if p == CATALOG:
            continue
        content = p.read_text(encoding="utf-8-sig", errors="replace")
        rel = p.relative_to(ROOT).as_posix()
        kind, purpose, current, update = classification(p, content)
        isdoc = p.suffix.lower() in {".md", ".txt"} and not p.name.startswith("requirements") or p.name == "27_FINAL_AUDIT_RESULTS.json"
        if isdoc:
            docs += 1
            lines.append(f"| `{rel}` | {purpose} | {kind} | {current} | {update} |")
        # Do not index this checker or generated report prose recursively.
        if p == Path(__file__).resolve() or p.parent == AUDIT and number(p) in {47, 49}:
            continue
        found = []
        for i, line in enumerate(content.splitlines(), 1):
            terms = sorted({m.group(0) for m in TERM.finditer(line)})
            if terms:
                found.append(f"{i}: " + ", ".join(terms))
                counts[kind] += len(list(TERM.finditer(line)))
        if found:
            matches.append((rel, kind, "; ".join(found)))
    lines += ["", "## Every retained old-scope match", "",
              "Search is case-insensitive and uses whole terms: RAG; Proactive Monitoring/Monitoring Agent; Arabic; Voice Support. Structured/unstructured variants match RAG. The broader Arabic term intentionally includes existing-language functionality. Match locations are file line numbers; only matched terms are reproduced, never source payloads or secret values.", "",
              "Scope: tracked and new first-party text up to 2 MB; excludes TimesFM, dependency/cache/runtime-data/backup trees, environment files and lock files. This catalog and the final report/checker's own search examples are excluded to avoid recursive matches. This is an explicit search boundary, not a claim to scan private data or third-party vendor code.", "",
              "| File | Class / reason above | Every matching line and term |", "|---|---|---|"]
    lines += [f"| `{rel}` | {kind} | {found} |" for rel, kind, found in matches]
    lines += ["", f"Inventory: {docs} documentation/reference files (excluding this catalog). Match counts: " + "; ".join(f"{k}={v}" for k, v in counts.items()) + f" across {len(matches)} files.", "",
              "Current B mentions were reviewed as explicit exclusions/deferrals or descriptions of historical conflicts. C bodies are superseded in their own files. A and D occurrences are intentionally retained; they cannot reintroduce a release milestone. No removed-feature implementation or deletion was performed.", ""]
    CATALOG.write_text("\n".join(lines), encoding="utf-8")
    print(f"Inventory written: {docs} docs, {len(matches)} matching files, counts {counts}")


def check(files):
    errors = []
    changed = set(git("diff", "--name-only", "--ignore-submodules=all")) | set(git("ls-files", "--others", "--exclude-standard"))
    checked = 0
    diagrams = 0
    for rel in sorted(changed):
        p = ROOT / rel
        if not p.is_file():
            continue
        # This checks documentation, not authorization for unrelated code diffs.
        # CI/test fixes are legitimate in subsequent tasks; review them separately.
        if p.suffix != ".md":
            continue
        body = p.read_text(encoding="utf-8-sig")
        kind = classification(p, body)[0]
        # Superseded bodies deliberately preserve old formatting and links.
        if kind == "C":
            body = body.split("\n\n", 1)[0]
        checked += 1
        fenced = False
        table_width = None
        for i, line in enumerate(body.splitlines(), 1):
            if line.startswith("```"):
                fenced = not fenced
                diagrams += line.strip() == "```mermaid"
            if "\ufffd" in line:
                errors.append(f"Replacement character: {rel}:{i}")
            if line.rstrip() != line and not line.endswith("  "):
                errors.append(f"Trailing whitespace: {rel}:{i}")
            if not fenced and line.startswith("|"):
                width = len(re.split(r"(?<!\\)\|", line))
                if table_width is not None and width != table_width:
                    errors.append(f"Table width: {rel}:{i}")
                table_width = width
            else:
                table_width = None
        if fenced:
            errors.append(f"Unclosed fence: {rel}")
        for link in re.findall(r"\[[^\]]*\]\(([^\s)]+)\)", body):
            target = unquote(link.split("#")[0])
            if not target or re.match(r"[a-z]+://", target):
                continue
            if not (p.parent / target).exists():
                errors.append(f"Missing relative link: {rel}: {target}")
    for prefix in ("43_", "45_"):
        p = next(AUDIT.glob(prefix + "*.md"))
        caps = re.findall(r"^\| (CAP-\d\d)\b", p.read_text(encoding="utf-8"), re.M)
        if caps != [f"CAP-{i:02d}" for i in range(1, 15)]:
            errors.append(f"Capability rows missing/duplicate/out of order: {p.name}")
    for prefix in ("34_", "43_", "45_"):
        p = next(AUDIT.glob(prefix + "*.md"))
        body = p.read_text(encoding="utf-8")
        for required in ("DEFERRED_TO_PRODUCTION_READINESS", "NO-GO", "G-C-DEPLOY"):
            if required not in body:
                errors.append(f"Missing local/deployment status distinction ({required}): {p.name}")
        for obsolete in ("No CDC before C closure", "no CDC implementation before C external closure",
                         "Next exact implementation phase is P0 Foundation-C external closure"):
            if obsolete in body:
                errors.append(f"Obsolete local entry blocker: {p.name}")
    oldmap = "\n".join(git("show", "HEAD:BIAVORA_PRODUCTION_READINESS_AUDIT/26_MASTER_REFACTOR_BUILD_DELETE_PLAN.md"))
    newmap = next(AUDIT.glob("26_*.md")).read_text(encoding="utf-8")
    missing = set(re.findall(r"MAP-\d{3}", oldmap)) - set(re.findall(r"MAP-\d{3}", newmap))
    if missing:
        errors.append(f"Lost stable MAP IDs: {sorted(missing)}")
    debt = next(AUDIT.glob("20_*.md")).read_text(encoding="utf-8")
    if set(re.findall(r"^\| (BIA-\d{3})", debt, re.M)) != {f"BIA-{i:03d}" for i in range(1, 43)}:
        errors.append("Stable debt register rows missing")
    for rel in changed:
        p = ROOT / rel
        if p.parent == AUDIT and number(p) in set(range(0, 8)) | set(range(15, 20)) | {27, 28, 35} | set(range(36, 43)):
            errors.append(f"Historical evidence changed: {rel}")
    print(f"Checked {checked} changed Markdown files; {diagrams} Mermaid blocks (structural only, not rendered).")
    for error in errors:
        print("ERROR:", error)
    if errors:
        raise SystemExit(1)
    print("PASS: links, fences, tables, text hygiene, scope rows, stable IDs and historical immutability.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write-inventory", action="store_true")
    args = parser.parse_args()
    selected = paths()
    if args.write_inventory:
        inventory(selected)
    check(selected)
